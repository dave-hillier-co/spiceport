using Grpc.Core;
using Spiceport.Core;
using Spiceport.Datastore;
using Spiceport.Grains;
using V1 = Authzed.Api.V1;
using CoreUpdateOperation = Spiceport.Core.UpdateOperation;

namespace Spiceport.Api;

/// <summary>
/// gRPC front door for the <c>authzed.api.v1.WatchService</c>. Server-streaming Watch tails the
/// silo-singleton <see cref="IDatastore.Watch"/> directly (a long-lived stream is a poor fit for a
/// request/response grain). Each emitted <see cref="V1::WatchResponse"/> carries its own ZedToken
/// (<c>changes_through</c>) so a client can resume exactly once after a disconnect. v1 deltas vs the
/// internal Watch: filter emitted updates by <c>optional_object_types</c> or, mutually exclusively, by
/// <c>optional_relationship_filters</c> (an update is emitted when it matches any filter); no
/// <c>schema_updated</c> field (this snapshot watches relationships only).
/// </summary>
public sealed class AuthzedWatchV1Service(IDatastore datastore, ISchemaProvider schemaProvider)
    : V1::WatchService.WatchServiceBase
{
    public override async Task Watch(
        V1::WatchRequest request,
        IServerStreamWriter<V1::WatchResponse> responseStream,
        ServerCallContext context)
    {
        ArgumentNullException.ThrowIfNull(request);

        // SpiceDB's WatchService registers the protoc-gen-validate stream interceptor, which validates the
        // request before the handler runs; WatchRequest has no consistency field and no handwritten rules.
        RequestValidation.Validate(request);

        var cancellationToken = context.CancellationToken;

        // Upstream (internal/services/v1/watch.go) rejects object types combined with relationship filters
        // whenever relationship updates are being watched, before the start cursor is resolved.
        if (IncludesRelationshipUpdates(request) &&
            request.OptionalObjectTypes.Count > 0 && request.OptionalRelationshipFilters.Count > 0)
        {
            throw new RpcException(new Status(
                StatusCode.InvalidArgument,
                "cannot specify both object types and relationship filters"));
        }

        // Empty => no filter; otherwise emit only updates whose resource object type is in the set.
        var objectTypeFilter = request.OptionalObjectTypes.Count == 0
            ? null
            : new HashSet<string>(request.OptionalObjectTypes);

        // Resolve the start cursor: a supplied token decodes to its revision (rejecting a mismatched
        // datastore); otherwise start from current head so only future writes are tailed.
        IRevision afterRevision;
        if (request.OptionalStartCursor is { Token.Length: > 0 } cursor)
        {
            var parser = await datastore.GetRevisionParser(cancellationToken);
            if (GoBase64.CorruptInputOffset(cursor.Token) is { } offset)
                throw UndecodableStartCursor($"illegal base64 data at input byte {offset}");
            var decoded = ZedTokens.DecodeRevision(new Core.ZedToken(cursor.Token), parser);
            if (decoded.Status == ZedTokenStatus.Unknown)
                throw UndecodableStartCursor("malformed zedtoken");
            if (decoded.Status == ZedTokenStatus.MismatchedDatastoreId)
                throw new RpcException(new Status(
                    StatusCode.InvalidArgument,
                    "start revision was generated by a different datastore instance"));
            afterRevision = decoded.Revision;
        }
        else
        {
            var head = await datastore.HeadRevision(cancellationToken);
            afterRevision = head.Revision;
        }

        // Empty => no filter; otherwise emit only updates matching at least one filter. Built after
        // the cursor is resolved, as upstream does, so a bad cursor is reported ahead of a bad filter.
        // Each filter is validated against the schema first (upstream: validateRelationshipsFilter).
        IReadOnlyList<WatchRelationshipFilter>? relationshipFilters = null;
        if (request.OptionalRelationshipFilters.Count > 0)
        {
            var schema = schemaProvider.Current;
            relationshipFilters = request.OptionalRelationshipFilters
                .Select(filter =>
                {
                    ValidateRelationshipFilter(schema, filter);
                    return ToWatchFilter(filter);
                })
                .ToList();
        }

        var datastoreId = await datastore.GetUniqueId(cancellationToken);
        var options = new WatchOptions(ResolveContent(request));

        // The datastore Watch is a lazy iterator: cursor-validity and watch-enablement checks throw on
        // the first MoveNextAsync, not at GetAsyncEnumerator, so the catch must wrap the iteration.
        var enumerator = datastore.Watch(afterRevision, options, cancellationToken).GetAsyncEnumerator(cancellationToken);
        try
        {
            while (true)
            {
                bool moved;
                try
                {
                    moved = await enumerator.MoveNextAsync();
                }
                catch (OperationCanceledException)
                {
                    break;
                }
                catch (RevisionNotFoundException ex)
                {
                    // The cursor is older than the retained GC window — cannot replay from it.
                    throw new RpcException(new Status(StatusCode.FailedPrecondition, ex.Message));
                }
                catch (WatchDisabledException ex)
                {
                    // The backend cannot support Watch (e.g. Postgres without track_commit_timestamp=on).
                    throw new RpcException(new Status(StatusCode.FailedPrecondition, ex.Message));
                }

                if (!moved)
                    break;

                if (cancellationToken.IsCancellationRequested)
                    break;

                var change = enumerator.Current;
                var response = ToResponse(change, datastoreId, objectTypeFilter, relationshipFilters);

                // Checkpoints always flow through (they carry revision-progress liveness for filtered
                // consumers). Otherwise skip a content response whose every update was filtered out.
                if (!change.IsCheckpoint && response.Updates.Count == 0 &&
                    !change.SchemaChanged && (objectTypeFilter is not null || relationshipFilters is not null))
                {
                    continue;
                }

                await responseStream.WriteAsync(response);
            }
        }
        finally
        {
            await enumerator.DisposeAsync();
        }
    }

    private V1::WatchResponse ToResponse(
        RevisionChange change,
        string datastoreId,
        HashSet<string>? objectTypeFilter,
        IReadOnlyList<WatchRelationshipFilter>? relationshipFilters)
    {
        var token = ZedTokens.FromRevision(change.Revision, schemaProvider.Current.SchemaHash, datastoreId);
        var response = new V1::WatchResponse
        {
            ChangesThrough = new V1::ZedToken { Token = token.Token },
            SchemaUpdated = change.SchemaChanged,
            IsCheckpoint = change.IsCheckpoint,
        };

        // SpiceDB (internal/services/v1/watch.go) puts the change's transaction metadata on every response it
        // sends for the change: the whole list as full_revision_metadata, and optional_transaction_metadata
        // when the list has exactly one entry. A revision here is one transaction, so the list is that
        // transaction's metadata or empty; a checkpoint change, here as there, carries none.
        if (change.TransactionMetadata is { } metadata)
        {
            var parsed = Google.Protobuf.WellKnownTypes.Struct.Parser.ParseFrom(metadata);
            response.OptionalTransactionMetadata = parsed;
            response.FullRevisionMetadata.Add(parsed);
        }

        // A checkpoint carries no content, only the revision.
        if (change.IsCheckpoint)
            return response;

        foreach (var update in change.RelationshipChanges)
        {
            if (objectTypeFilter is not null &&
                !objectTypeFilter.Contains(update.Relationship.Resource.ObjectType))
            {
                continue;
            }

            if (relationshipFilters is not null &&
                !relationshipFilters.Any(filter => filter.Matches(update.Relationship)))
            {
                continue;
            }

            response.Updates.Add(ToProto(update));
        }

        return response;
    }

    /// <summary>
    /// True when the request watches relationship updates: an empty selector, or one naming
    /// <c>WATCH_KIND_UNSPECIFIED</c> or <c>WATCH_KIND_INCLUDE_RELATIONSHIP_UPDATES</c>.
    /// </summary>
    private static bool IncludesRelationshipUpdates(V1::WatchRequest request) =>
        request.OptionalUpdateKinds.Count == 0 ||
        request.OptionalUpdateKinds.Any(kind =>
            kind is V1::WatchKind.Unspecified or V1::WatchKind.IncludeRelationshipUpdates);

    /// <summary>
    /// A converted v1 relationship filter. The core <see cref="SubjectRelationFilter"/> cannot say
    /// "ellipsis only" (its ellipsis-only shape is the same value as <see cref="SubjectRelationFilter.Any"/>),
    /// so a subject filter whose <c>optional_relation</c> is present but empty is carried as
    /// <paramref name="SubjectEllipsisOnly"/> and enforced here.
    /// </summary>
    private sealed record WatchRelationshipFilter(RelationshipsFilter Filter, bool SubjectEllipsisOnly)
    {
        public bool Matches(Relationship relationship) =>
            Filter.Matches(relationship) &&
            (!SubjectEllipsisOnly || relationship.Subject.Relation == CoreConstants.Ellipsis);
    }

    /// <summary>
    /// Validates a v1 <see cref="V1::RelationshipFilter"/> as upstream's
    /// <c>validateRelationshipsFilter</c> does, in its order: the resource type and relation, then the
    /// subject type and relation, must exist in the schema (FailedPrecondition otherwise); resource id
    /// and resource id prefix are mutually exclusive; and at least one field must be set
    /// (InvalidArgument for either).
    /// </summary>
    private static void ValidateRelationshipFilter(SchemaSnapshot schema, V1::RelationshipFilter f)
    {
        CheckFilterComponent(schema, f.ResourceType, f.OptionalRelation);

        if (f.OptionalSubjectFilter is { } sub)
            CheckFilterComponent(schema, sub.SubjectType, sub.OptionalRelation?.Relation ?? string.Empty);

        if (!string.IsNullOrEmpty(f.OptionalResourceId) && !string.IsNullOrEmpty(f.OptionalResourceIdPrefix))
            throw InvalidFilter("resource_id and resource_id_prefix cannot be set at the same time", f);

        if (string.IsNullOrEmpty(f.ResourceType) && string.IsNullOrEmpty(f.OptionalResourceId) &&
            string.IsNullOrEmpty(f.OptionalResourceIdPrefix) && string.IsNullOrEmpty(f.OptionalRelation) &&
            f.OptionalSubjectFilter is null)
        {
            throw InvalidFilter("at least one field must be set", f);
        }
    }

    /// <summary>
    /// Upstream's <c>checkFilterComponent</c>: an empty type places no constraint; otherwise the type must
    /// exist, and the relation must too, with an empty relation standing for the ellipsis.
    /// </summary>
    private static void CheckFilterComponent(SchemaSnapshot schema, string objectType, string optionalRelation)
    {
        if (string.IsNullOrEmpty(objectType))
            return;

        var allowEllipsis = optionalRelation.Length == 0;
        SchemaValidation.CheckNamespaceAndRelations(
            schema,
            new SchemaValidation.TypeAndRelation(
                objectType, allowEllipsis ? CoreConstants.Ellipsis : optionalRelation, allowEllipsis));
    }

    /// <summary>
    /// SpiceDB's <c>InvalidFilterError</c>: INVALID_ARGUMENT with ERROR_REASON_INVALID_FILTER and the filter's
    /// Go <c>String()</c> as its <c>filter</c> metadata.
    /// </summary>
    private static RpcException InvalidFilter(string reason, V1::RelationshipFilter filter) =>
        RpcErrors.WithReason(
            StatusCode.InvalidArgument,
            $"the relationship filter provided is not valid: {reason}",
            V1::ErrorReason.InvalidFilter,
            [new("filter", GoPrototext.Format(filter))]);

    /// <summary>
    /// Upstream's start-cursor decode failure: <c>failed to decode start revision: %s</c> over zedtoken's
    /// <c>error decoding zedtoken: %w</c>. A token that is not base64 reports Go's decoder error exactly; one
    /// that is base64 but not a token is SpiceDB's protobuf unmarshal error there, which Spiceport's own token
    /// format cannot reproduce, so it reports <paramref name="cause"/> in the same frame.
    /// </summary>
    private static RpcException UndecodableStartCursor(string cause) =>
        new(new Status(
            StatusCode.InvalidArgument, $"failed to decode start revision: error decoding zedtoken: {cause}"));

    /// <summary>
    /// Maps a validated v1 <see cref="V1::RelationshipFilter"/> as upstream's
    /// <c>RelationshipsFilterFromPublicFilter</c> does: an empty field places no constraint; a subject
    /// filter's present-but-empty <c>optional_relation</c> selects only the ellipsis relation, a non-empty
    /// one selects exactly that relation, and an absent one selects any relation.
    /// </summary>
    private static WatchRelationshipFilter ToWatchFilter(V1::RelationshipFilter f)
    {
        IReadOnlyList<SubjectsSelector>? selectors = null;
        var subjectEllipsisOnly = false;
        if (f.OptionalSubjectFilter is { } sub)
        {
            SubjectRelationFilter? relationFilter = null;
            if (sub.OptionalRelation is { } relation)
            {
                if (relation.Relation.Length == 0)
                    subjectEllipsisOnly = true;
                else
                    relationFilter = new SubjectRelationFilter(NonEllipsisRelation: relation.Relation);
            }

            selectors =
            [
                new SubjectsSelector(
                    NullIfEmpty(sub.SubjectType),
                    string.IsNullOrEmpty(sub.OptionalSubjectId) ? null : [sub.OptionalSubjectId],
                    relationFilter),
            ];
        }

        var filter = new RelationshipsFilter
        {
            OptionalResourceType = NullIfEmpty(f.ResourceType),
            OptionalResourceIds = string.IsNullOrEmpty(f.OptionalResourceId) ? null : [f.OptionalResourceId],
            OptionalResourceIdPrefix = NullIfEmpty(f.OptionalResourceIdPrefix),
            OptionalResourceRelation = NullIfEmpty(f.OptionalRelation),
            OptionalSubjectsSelectors = selectors,
        };
        return new WatchRelationshipFilter(filter, subjectEllipsisOnly);
    }

    private static string? NullIfEmpty(string value) => string.IsNullOrEmpty(value) ? null : value;

    /// <summary>
    /// Maps the request's <c>optional_update_kinds</c> to the datastore's <see cref="WatchContent"/>.
    /// An empty selector defaults to relationships only (backwards-compatible).
    /// </summary>
    private static WatchContent ResolveContent(V1::WatchRequest request)
    {
        if (request.OptionalUpdateKinds.Count == 0)
            return WatchContent.Relationships;

        WatchContent content = 0;
        foreach (var kind in request.OptionalUpdateKinds)
        {
            content |= kind switch
            {
                V1::WatchKind.IncludeSchemaUpdates => WatchContent.Schema,
                V1::WatchKind.IncludeCheckpoints => WatchContent.Checkpoints,
                _ => WatchContent.Relationships,
            };
        }

        // No additive fallback needed here: the datastore's checkpoint emission (see
        // IDatastore.Watch/WatchOptions) is keyed off commit activity itself, not off whether the
        // requested content flags matched anything, so a checkpoints-only (or schema-only) mask still
        // sees checkpoints emitted on every commit.
        return content;
    }

    private static V1::RelationshipUpdate ToProto(Core.RelationshipUpdate update)
    {
        var op = update.Operation switch
        {
            CoreUpdateOperation.Create => V1::RelationshipUpdate.Types.Operation.Create,
            CoreUpdateOperation.Delete => V1::RelationshipUpdate.Types.Operation.Delete,
            _ => V1::RelationshipUpdate.Types.Operation.Touch,
        };
        return new V1::RelationshipUpdate { Operation = op, Relationship = ToProto(update.Relationship) };
    }

    private static V1::Relationship ToProto(Core.Relationship rel)
    {
        var subjectRelation = rel.Subject.Relation == CoreConstants.Ellipsis ? string.Empty : rel.Subject.Relation;
        var proto = new V1::Relationship
        {
            Resource = new V1::ObjectReference
            {
                ObjectType = rel.Resource.ObjectType,
                ObjectId = rel.Resource.ObjectId,
            },
            Relation = rel.Resource.Relation,
            Subject = new V1::SubjectReference
            {
                Object = new V1::ObjectReference
                {
                    ObjectType = rel.Subject.ObjectType,
                    ObjectId = rel.Subject.ObjectId,
                },
                OptionalRelation = subjectRelation,
            },
        };

        if (rel.OptionalCaveat is { } caveat)
        {
            var pc = new V1::ContextualizedCaveat { CaveatName = caveat.CaveatName };
            if (DictToStruct(caveat.Context) is { } ctx)
                pc.Context = ctx;
            proto.OptionalCaveat = pc;
        }

        if (rel.OptionalExpiration is { } expiration)
            proto.OptionalExpiresAt = Google.Protobuf.WellKnownTypes.Timestamp.FromDateTimeOffset(expiration);

        return proto;
    }

    private static Google.Protobuf.WellKnownTypes.Struct? DictToStruct(IReadOnlyDictionary<string, object?>? dict)
    {
        if (dict is null || dict.Count == 0)
            return null;

        var s = new Google.Protobuf.WellKnownTypes.Struct();
        foreach (var (k, v) in dict)
            s.Fields[k] = ObjectToValue(v);
        return s;
    }

    private static Google.Protobuf.WellKnownTypes.Value ObjectToValue(object? o) =>
        o switch
        {
            null => Google.Protobuf.WellKnownTypes.Value.ForNull(),
            bool b => Google.Protobuf.WellKnownTypes.Value.ForBool(b),
            string str => Google.Protobuf.WellKnownTypes.Value.ForString(str),
            double d => Google.Protobuf.WellKnownTypes.Value.ForNumber(d),
            int i => Google.Protobuf.WellKnownTypes.Value.ForNumber(i),
            long l => Google.Protobuf.WellKnownTypes.Value.ForNumber(l),
            IReadOnlyDictionary<string, object?> map =>
                Google.Protobuf.WellKnownTypes.Value.ForStruct(DictToStruct(map) ?? new Google.Protobuf.WellKnownTypes.Struct()),
            System.Collections.IEnumerable list =>
                Google.Protobuf.WellKnownTypes.Value.ForList(list.Cast<object?>().Select(ObjectToValue).ToArray()),
            _ => Google.Protobuf.WellKnownTypes.Value.ForString(o.ToString() ?? string.Empty),
        };
}
